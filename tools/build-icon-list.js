// Writes js/core/icon-list.js: every Minecraft texture key the app can show.
// Used by the service worker (offline cache) and tools/fetch-icons.js (local copies).
// Run after adding icons:  node tools/build-icon-list.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.join(__dirname, '..');

const ctx = { window: {}, location: { protocol: 'https:' }, console };
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ['js/data/enchantments.js', 'js/data/villagers.js', 'js/data/trims.js', 'js/data/items.js', 'js/core/icons.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
}
const { TH } = ctx;
const keys = new Set([...Object.keys(TH.icon.aliases), ...Object.keys(TH.icon.external)]);

TH.data.professions.forEach((p) => keys.add(TH.icon.profKey(p.id)));
keys.add(TH.icon.profKey('none'));
TH.data.items.forEach((it) => (it.materials || ['plain']).forEach((m) => keys.add(TH.icon.itemKey(it.id, m))));
Object.values(TH.data.materials || {}).forEach((m) => { if (m && typeof m.icon === 'string') keys.add(m.icon); });
TH.data.trimPatterns.forEach((p) => keys.add(TH.icon.trimKey(p.id)));
TH.data.trimMaterials.forEach((m) => keys.add(TH.icon.trimMaterialKey(m.item)));

// literal keys used directly in the code: TH.icon('…'), mc:… nav icons, CSS-free strings
const literal = /TH\.icon\(\s*'([^']+)'|icon:\s*'mc:([^']+)'/g;
for (const dir of ['js/modules', 'js/core']) {
  for (const f of fs.readdirSync(path.join(root, dir))) {
    const src = fs.readFileSync(path.join(root, dir, f), 'utf8');
    for (const m of src.matchAll(literal)) keys.add(m[1] || m[2]);
  }
}

// icons named in data tables ('item/hopper', 'block/mud' …): every item/ and block/ literal in modules and data
const lit2 = /'((?:item|block)\/[a-z0-9_]+)'/g;
for (const dir of ['js/modules', 'js/data']) {
  for (const f of fs.readdirSync(path.join(root, dir))) {
    if (!f.endsWith('.js')) continue;
    for (const m of fs.readFileSync(path.join(root, dir, f), 'utf8').matchAll(lit2)) keys.add(m[1]);
  }
}

const list = [...keys].sort();
fs.writeFileSync(path.join(root, 'js/core/icon-list.js'),
  '// Generated by tools/build-icon-list.js — every texture key the app can show.\nwindow.TH = window.TH || {};\nTH.iconList = ' + JSON.stringify(list, null, 0).replace(/","/g, '", "') + ';\n');
console.log(list.length + ' icon keys written');
